export type ScenarioId =
  | "word_mastered"
  | "word_mastered_phrase"
  | "word_mastered_writing"
  | "word_mastered_writing_phrase"
  | "word_mistake"
  | "phrase_quiz";

export type DialogReply = {
  label: string;
  /** Сколько привязанности дать за этот ответ. */
  bond?: number;
  /**
   * Произнести слово вслух. Это действие, а не ответ: диалог остаётся
   * на месте, кнопку можно нажимать повторно.
   */
  speak?: boolean;
  /** Добавить слово в «Повторение». */
  review?: boolean;
  /** Пул ответных реплик панды. Если его нет — диалог просто закрывается. */
  response?: string[];
  /** Только для вариантов квиза: верный ли это ответ. */
  isCorrect?: boolean;
};

export type DialogScenario = {
  /** Пул первых реплик. Показывается одна, случайно, без повтора подряд. */
  lines: string[];
  /** Реплики на случай, когда за тренировку освоено сразу несколько слов. */
  manyLines?: string[];
  /** Кнопки ответа. Если выбор сейчас не разрешён, показывается только «Понятно!». */
  replies: DialogReply[];
  /** Квиз: реплики после верного ответа. */
  correctLines?: string[];
  /** Квиз: реплики после неверного ответа. */
  wrongLines?: string[];
};

